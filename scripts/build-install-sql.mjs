// Joins the migrations and the seed into one file, supabase/install.sql, that
// can be pasted into the Supabase SQL editor (or run with psql) in one go.
//
// The site shares a Supabase project with another application, which has its
// own migration history. Installing from this single file keeps the site's
// schema out of that history: nothing here is recorded as a migration.
//
// The file runs in one transaction, so a failure part-way leaves nothing behind.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const migrations = readdirSync(join(root, 'supabase/migrations')).sort();
const part = (path) => `-- ===== ${path} =====\n\n${readFileSync(join(root, path), 'utf8').trim()}\n`;

const sql = `-- Generated by scripts/build-install-sql.mjs. Do not edit by hand.
--
-- Installs the LSI Corp website's database: everything is created inside the
-- "lsicorp" schema, plus one storage bucket ("lsicorp-release-files") and its
-- three policies. Nothing in "public" or any other schema is created, changed
-- or re-granted.
--
-- Run once on a project that does not have the "lsicorp" schema yet.
-- To remove it again: supabase/uninstall.sql.

begin;

do $$
begin
  if exists (select 1 from pg_namespace where nspname = 'lsicorp') then
    raise exception 'The "lsicorp" schema already exists. This file is for a first install only.';
  end if;
end
$$;

${migrations.map((file) => part(`supabase/migrations/${file}`)).join('\n')}
${part('supabase/seed.sql')}
commit;
`;

writeFileSync(join(root, 'supabase/install.sql'), sql);

writeFileSync(
  join(root, 'supabase/uninstall.sql'),
  `-- Removes everything supabase/install.sql created. Deletes all of the site's
-- content, releases, enquiries and audit history. There is no undo.
-- Files uploaded to the "lsicorp-release-files" bucket must be removed from
-- the Storage page of the dashboard first; then delete the bucket there.

begin;
drop policy if exists "lsicorp: release managers add release files" on storage.objects;
drop policy if exists "lsicorp: release managers replace release files" on storage.objects;
drop policy if exists "lsicorp: admins remove release files" on storage.objects;
drop schema if exists lsicorp cascade;
commit;
`,
);

console.log(`supabase/install.sql written (${migrations.length} migrations + seed, ${(sql.length / 1024).toFixed(0)} KB)`);
